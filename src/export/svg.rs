//! Architectural floor plans as SVG, one per floor.
//!
//! North is up, so the street front (south) is at the bottom of the drawing.

use std::fmt::Write as _;

use crate::geometry::{Axis, Rect, Side};
use crate::model::*;

/// Pixels per metre.
const SCALE: f64 = 40.0;
const PAD: f64 = 40.0;
const HEADER: f64 = 70.0;
const FOOTER: f64 = 40.0;

const INK: &str = "#3B342C";
const PAPER: &str = "#FBF8F2";

/// The floor plan of every floor, ground floor first.
pub fn floor_plans(building: &Building) -> Vec<String> {
    building
        .floors
        .iter()
        .map(|f| floor_plan_svg(building, f))
        .collect()
}

pub fn floor_plan_svg(b: &Building, floor: &Floor) -> String {
    let bounds = b.garden.as_ref().map_or(b.footprint.grow(2.0), |g| g.lot);
    let view = View {
        min_x: bounds.x,
        max_z: bounds.z1(),
    };
    let width = bounds.w * SCALE + 2.0 * PAD;
    let height = bounds.d * SCALE + 2.0 * PAD + HEADER + FOOTER;
    let title = format!(
        "Urbanitas · {} {} · {}",
        b.params.style.label(),
        b.params.building_type.label(),
        floor.name()
    );

    let mut s = String::new();
    let _ = writeln!(
        s,
        r#"<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0}" height="{height:.0}" viewBox="0 0 {width:.0} {height:.0}" font-family="Helvetica, Arial, sans-serif">"#
    );
    let _ = writeln!(s, "<title>{}</title>", esc(&title));
    let _ = writeln!(
        s,
        "<desc>Generated by Urbanitas (Noj Suon), seed {}</desc>",
        b.params.seed
    );
    let _ = writeln!(s, r#"<rect width="100%" height="100%" fill="{PAPER}"/>"#);
    let _ = writeln!(
        s,
        r#"<text x="{PAD}" y="34" font-size="20" font-weight="bold" fill="{INK}">{}</text>"#,
        esc(&title)
    );
    let _ = writeln!(
        s,
        r##"<text x="{PAD}" y="56" font-size="12" fill="#7A6F60">seed {} · {:.1} × {:.1} m · {} floor(s) · {} roof · {}</text>"##,
        b.params.seed,
        b.footprint.w,
        b.footprint.d,
        b.floors.len(),
        b.roof.label(),
        esc(&b.palette.name)
    );

    if let Some(garden) = &b.garden {
        if floor.level == 0 {
            garden_layer(&mut s, &view, garden);
        } else {
            let (x, y, w, h) = view.rect(&garden.lot);
            let _ = writeln!(
                s,
                r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="none" stroke="#CFC6B5" stroke-dasharray="6 4"/>"##
            );
        }
    }

    for balcony in &floor.balconies {
        let rect = balcony_rect(b, balcony);
        let (x, y, w, h) = view.rect(&rect);
        let _ = writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#E9E1D3" stroke="#8A7F70" stroke-dasharray="4 3"/>"##
        );
    }

    for room in &floor.rooms {
        let (x, y, w, h) = view.rect(&room.rect);
        let _ = writeln!(
            s,
            r#"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="{}"/>"#,
            room_color(room.kind)
        );
        if room.kind == RoomKind::Stairs {
            stair_hatching(
                &mut s,
                &view,
                &room.rect,
                floor.level as usize + 1 < b.floors.len(),
            );
        }
    }

    // Partitions, broken at their doors.
    let partition = b.style.partition_thickness * SCALE;
    for wall in &floor.walls {
        let seg = wall.segment;
        let mut pieces = vec![(seg.start, seg.end)];
        if let Some(door) = wall.door {
            let (d0, d1) = (
                door.center - door.width / 2.0,
                door.center + door.width / 2.0,
            );
            pieces = vec![(seg.start, d0), (d1, seg.end)];
            door_swing(&mut s, &view, seg.axis, seg.coord, d0, door.width);
        }
        for (u0, u1) in pieces.into_iter().filter(|(u0, u1)| u1 > u0) {
            let (p, q) = (
                view.along(seg.axis, seg.coord, u0),
                view.along(seg.axis, seg.coord, u1),
            );
            let _ = writeln!(
                s,
                r#"<line x1="{:.1}" y1="{:.1}" x2="{:.1}" y2="{:.1}" stroke="{INK}" stroke-width="{partition:.1}"/>"#,
                p.0, p.1, q.0, q.1
            );
        }
    }

    // Exterior walls, then openings drawn over them.
    let t = b.style.wall_thickness;
    let fp = b.footprint;
    for band in [
        Rect::new(fp.x, fp.z, fp.w, t),
        Rect::new(fp.x, fp.z1() - t, fp.w, t),
        Rect::new(fp.x, fp.z, t, fp.d),
        Rect::new(fp.x1() - t, fp.z, t, fp.d),
    ] {
        let (x, y, w, h) = view.rect(&band);
        let _ = writeln!(
            s,
            r#"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="{INK}"/>"#
        );
    }
    for opening in &floor.openings {
        let gap = opening_rect(b, opening);
        let (x, y, w, h) = view.rect(&gap);
        match opening.kind {
            OpeningKind::Door => {
                let _ = writeln!(
                    s,
                    r#"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="{PAPER}"/>"#
                );
            }
            _ => {
                let _ = writeln!(
                    s,
                    r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#DCEFF7" stroke="{INK}" stroke-width="1"/>"##
                );
            }
        }
    }

    for room in &floor.rooms {
        let (cx, cz) = room.rect.center();
        let (x, y) = (view.x(cx), view.y(cz));
        let size = if room.rect.min_side() < 2.2 { 9 } else { 12 };
        let _ = writeln!(
            s,
            r#"<text x="{x:.1}" y="{y:.1}" font-size="{size}" text-anchor="middle" fill="{INK}">{}</text>"#,
            room.kind.label()
        );
        let _ = writeln!(
            s,
            r##"<text x="{x:.1}" y="{:.1}" font-size="{}" text-anchor="middle" fill="#7A6F60">{:.1} m²</text>"##,
            y + size as f64 + 2.0,
            size - 2,
            room.area
        );
    }

    // Compass and scale bar.
    let (nx, ny) = (width - PAD - 10.0, HEADER - 30.0);
    let _ = writeln!(
        s,
        r#"<path d="M {nx:.1} {:.1} L {:.1} {:.1} L {nx:.1} {:.1} L {:.1} {:.1} Z" fill="{INK}"/>"#,
        ny - 14.0,
        nx + 7.0,
        ny + 8.0,
        ny + 3.0,
        nx - 7.0,
        ny + 8.0
    );
    let _ = writeln!(
        s,
        r#"<text x="{nx:.1}" y="{:.1}" font-size="11" text-anchor="middle" fill="{INK}">N</text>"#,
        ny + 22.0
    );
    let bar_y = height - FOOTER / 2.0;
    let _ = writeln!(
        s,
        r#"<line x1="{PAD}" y1="{bar_y:.1}" x2="{:.1}" y2="{bar_y:.1}" stroke="{INK}" stroke-width="3"/>"#,
        PAD + 5.0 * SCALE
    );
    let _ = writeln!(
        s,
        r#"<text x="{:.1}" y="{:.1}" font-size="11" fill="{INK}">5 m</text>"#,
        PAD + 5.0 * SCALE + 8.0,
        bar_y + 4.0
    );
    let _ = writeln!(
        s,
        r##"<text x="{:.1}" y="{:.1}" font-size="10" text-anchor="end" fill="#7A6F60">Urbanitas · Noj Suon</text>"##,
        width - PAD,
        bar_y + 4.0
    );
    s.push_str("</svg>\n");
    s
}

struct View {
    min_x: f64,
    max_z: f64,
}

impl View {
    fn x(&self, x: f64) -> f64 {
        PAD + (x - self.min_x) * SCALE
    }

    fn y(&self, z: f64) -> f64 {
        HEADER + PAD + (self.max_z - z) * SCALE
    }

    fn rect(&self, r: &Rect) -> (f64, f64, f64, f64) {
        (self.x(r.x), self.y(r.z1()), r.w * SCALE, r.d * SCALE)
    }

    /// The point `u` along a wall line on `axis` at `coord`.
    fn along(&self, axis: Axis, coord: f64, u: f64) -> (f64, f64) {
        match axis {
            Axis::X => (self.x(u), self.y(coord)),
            Axis::Z => (self.x(coord), self.y(u)),
        }
    }
}

/// A door leaf and its quarter-circle swing, hinged at `u0`.
fn door_swing(s: &mut String, view: &View, axis: Axis, coord: f64, u0: f64, width: f64) {
    let hinge = view.along(axis, coord, u0);
    let end = view.along(axis, coord, u0 + width);
    let leaf = match axis {
        Axis::X => (view.x(u0), view.y(coord + width)),
        Axis::Z => (view.x(coord + width), view.y(u0)),
    };
    let r = width * SCALE;
    let (a, b) = (
        (leaf.0 - hinge.0, leaf.1 - hinge.1),
        (end.0 - hinge.0, end.1 - hinge.1),
    );
    let sweep = if a.0 * b.1 - a.1 * b.0 > 0.0 { 1 } else { 0 };
    let _ = writeln!(
        s,
        r##"<path d="M {:.1} {:.1} L {:.1} {:.1} A {r:.1} {r:.1} 0 0 {sweep} {:.1} {:.1}" fill="none" stroke="#8A7F70" stroke-width="1"/>"##,
        hinge.0, hinge.1, leaf.0, leaf.1, end.0, end.1
    );
}

fn stair_hatching(s: &mut String, view: &View, r: &Rect, goes_up: bool) {
    let treads = (r.d / 0.28).floor() as usize;
    for i in 1..treads {
        let z = r.z + r.d * i as f64 / treads as f64;
        let _ = writeln!(
            s,
            r##"<line x1="{:.1}" y1="{:.1}" x2="{:.1}" y2="{:.1}" stroke="#A89D8C" stroke-width="1"/>"##,
            view.x(r.x),
            view.y(z),
            view.x(r.x1()),
            view.y(z)
        );
    }
    let (cx, cz) = r.center();
    let label = if goes_up { "UP ↑" } else { "↓" };
    let _ = writeln!(
        s,
        r#"<text x="{:.1}" y="{:.1}" font-size="10" text-anchor="middle" fill="{INK}">{label}</text>"#,
        view.x(cx),
        view.y(cz) - 22.0
    );
}

fn garden_layer(s: &mut String, view: &View, garden: &GardenPlan) {
    let (x, y, w, h) = view.rect(&garden.lot);
    let _ = writeln!(
        s,
        r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#C9D39A" stroke="#9AAE6B"/>"##
    );
    for feature in &garden.features {
        let (x, y, w, h) = view.rect(&feature.rect);
        let (cx, cz) = feature.rect.center();
        let (px, py, radius) = (view.x(cx), view.y(cz), feature.rect.w * SCALE / 2.0);
        let _ = match feature.kind {
            FeatureKind::Path | FeatureKind::Terrace => writeln!(
                s,
                r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#E3D6BC" stroke="#C9B48F"/>"##
            ),
            FeatureKind::Pool => writeln!(
                s,
                r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" rx="4" fill="#8FCBE0" stroke="#C9B48F" stroke-width="5"/>"##
            ),
            FeatureKind::Pergola => {
                let mut out = writeln!(
                    s,
                    r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="none" stroke="#7A5230" stroke-width="2"/>"##
                );
                let slats = (feature.rect.w / 0.45).floor() as usize;
                for i in 1..slats {
                    let sx = x + w * i as f64 / slats as f64;
                    out = writeln!(
                        s,
                        r##"<line x1="{sx:.1}" y1="{y:.1}" x2="{sx:.1}" y2="{:.1}" stroke="#7A5230" stroke-width="1"/>"##,
                        y + h
                    );
                }
                out
            }
            FeatureKind::OliveTree => writeln!(
                s,
                r##"<circle cx="{px:.1}" cy="{py:.1}" r="{radius:.1}" fill="#9AA77A" fill-opacity="0.85" stroke="#6F7D52"/>"##
            ),
            FeatureKind::CypressTree => writeln!(
                s,
                r##"<circle cx="{px:.1}" cy="{py:.1}" r="{radius:.1}" fill="#3E5E36" stroke="#2F4F2A"/>"##
            ),
            FeatureKind::LemonTree => writeln!(
                s,
                r##"<circle cx="{px:.1}" cy="{py:.1}" r="{radius:.1}" fill="#6E9A45" stroke="#4F7A35"/><circle cx="{:.1}" cy="{:.1}" r="2.5" fill="#F2D33B"/>"##,
                px + radius * 0.3,
                py - radius * 0.2
            ),
            FeatureKind::Pot => writeln!(
                s,
                r##"<circle cx="{px:.1}" cy="{py:.1}" r="{radius:.1}" fill="#C0693F"/>"##
            ),
        };
    }
}

/// Where an opening cuts through the exterior wall, on the ground plane.
fn opening_rect(b: &Building, o: &Opening) -> Rect {
    let (fp, t) = (b.footprint, b.style.wall_thickness);
    match o.side {
        Side::South => Rect::new(o.start(), fp.z, o.width, t),
        Side::North => Rect::new(o.start(), fp.z1() - t, o.width, t),
        Side::West => Rect::new(fp.x, o.start(), t, o.width),
        Side::East => Rect::new(fp.x1() - t, o.start(), t, o.width),
    }
}

fn balcony_rect(b: &Building, balcony: &Balcony) -> Rect {
    let fp = b.footprint;
    let u0 = balcony.center - balcony.width / 2.0;
    match balcony.side {
        Side::South => Rect::new(u0, fp.z - balcony.depth, balcony.width, balcony.depth),
        Side::North => Rect::new(u0, fp.z1(), balcony.width, balcony.depth),
        Side::West => Rect::new(fp.x - balcony.depth, u0, balcony.depth, balcony.width),
        Side::East => Rect::new(fp.x1(), u0, balcony.depth, balcony.width),
    }
}

fn room_color(kind: RoomKind) -> &'static str {
    match kind {
        RoomKind::Living => "#F3D9B1",
        RoomKind::Lounge => "#F0CFA0",
        RoomKind::Kitchen => "#F6E7A8",
        RoomKind::Dining => "#F2DDB8",
        RoomKind::Bedroom => "#CFE0EE",
        RoomKind::Bathroom => "#BFE3E0",
        RoomKind::Study => "#DCD3EC",
        RoomKind::Hall => "#E8E1D6",
        RoomKind::Stairs => "#D9D2C5",
        RoomKind::Retail => "#F4C7A1",
        RoomKind::Storage => "#DDD6CB",
        RoomKind::Office => "#D7E4C9",
    }
}

fn esc(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}
