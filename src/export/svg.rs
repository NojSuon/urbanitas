//! Architectural floor plans as SVG, one per level, drawn from a [`Layout`]
//! so hand-placed parts appear too.
//!
//! North is up, so the street front (south) is at the bottom of the drawing.

use std::fmt::Write as _;

use crate::geometry::Rect;
use crate::model::{OpeningKind, RoomKind};
use crate::parts::*;

/// Pixels per metre.
const SCALE: f64 = 40.0;
const PAD: f64 = 40.0;
const HEADER: f64 = 70.0;
const FOOTER: f64 = 40.0;

const INK: &str = "#3B342C";
const PAPER: &str = "#FBF8F2";

/// The plan of every storey, ground floor first.
pub fn floor_plans(layout: &Layout) -> Vec<String> {
    (0..layout.levels())
        .map(|level| floor_plan_svg(layout, level))
        .collect()
}

pub fn level_name(level: u32) -> String {
    if level == 0 {
        "Ground floor".to_string()
    } else {
        format!("Floor {level}")
    }
}

pub fn floor_plan_svg(layout: &Layout, level: u32) -> String {
    let bounds = layout.bounds().grow(1.0);
    let view = View {
        min_x: bounds.x,
        max_z: bounds.z1(),
    };
    let width = bounds.w * SCALE + 2.0 * PAD;
    let height = bounds.d * SCALE + 2.0 * PAD + HEADER + FOOTER;
    let title = format!("Urbanitas · {} · {}", layout.name, level_name(level));

    let mut s = String::new();
    let _ = writeln!(
        s,
        r#"<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0}" height="{height:.0}" viewBox="0 0 {width:.0} {height:.0}" font-family="Georgia, 'Times New Roman', serif">"#
    );
    let _ = writeln!(s, "<title>{}</title>", esc(&title));
    let _ = writeln!(s, "<desc>Generated by Urbanitas (Noj Suon)</desc>");
    let _ = writeln!(s, r#"<rect width="100%" height="100%" fill="{PAPER}"/>"#);
    let _ = writeln!(
        s,
        r#"<text x="{PAD}" y="34" font-size="20" font-weight="bold" fill="{INK}">{}</text>"#,
        esc(&title)
    );
    let _ = writeln!(
        s,
        r##"<text x="{PAD}" y="56" font-size="12" fill="#7A6F60">{}</text>"##,
        esc(&layout.description)
    );

    // Ground: garden areas. Upper floors: the lot outline only.
    for part in layout.on_level(0) {
        match &part.kind {
            PartKind::Area(a) if level == 0 => area(&mut s, &view, a),
            PartKind::Area(a) if a.kind == AreaKind::Lawn => {
                let (x, y, w, h) = view.rect(&a.rect);
                let _ = writeln!(
                    s,
                    r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="none" stroke="#CFC6B5" stroke-dasharray="6 4"/>"##
                );
            }
            _ => {}
        }
    }

    for part in layout.on_level(level) {
        match &part.kind {
            PartKind::Floor(f) => {
                let (x, y, w, h) = view.rect(&f.rect);
                let _ = writeln!(
                    s,
                    r#"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="{}"/>"#,
                    room_color(f.room)
                );
            }
            PartKind::Stairs(st) => stairs(&mut s, &view, st),
            PartKind::Balcony(b) => {
                let t = layout
                    .host_wall(level, b.at)
                    .map_or(layout.style.wall_thickness, |(_, w)| w.thickness);
                let along = [b.facing[1], -b.facing[0]];
                let out = |k: f64, a: f64| {
                    let d = t / 2.0 + k;
                    view.point([
                        b.at[0] + b.facing[0] * d + along[0] * a,
                        b.at[1] + b.facing[1] * d + along[1] * a,
                    ])
                };
                let (half, depth) = (b.width / 2.0, b.depth);
                let pts = [
                    out(0.0, -half),
                    out(depth, -half),
                    out(depth, half),
                    out(0.0, half),
                ];
                let _ = writeln!(
                    s,
                    r##"<polygon points="{}" fill="#E9E1D3" stroke="#8A7F70" stroke-dasharray="4 3"/>"##,
                    polygon(&pts)
                );
            }
            _ => {}
        }
    }

    // The stair well rising from the level below.
    if level > 0 {
        for part in layout.on_level(level - 1) {
            if let PartKind::Stairs(st) = &part.kind {
                stairs(&mut s, &view, st);
            }
        }
    }

    for part in layout.on_level(level) {
        let PartKind::Wall(w) = &part.kind else {
            continue;
        };
        let (p, q) = (view.point(w.a), view.point(w.b));
        let cap = if w.exterior { "square" } else { "butt" };
        let _ = writeln!(
            s,
            r#"<line x1="{:.1}" y1="{:.1}" x2="{:.1}" y2="{:.1}" stroke="{INK}" stroke-width="{:.1}" stroke-linecap="{cap}"/>"#,
            p.0,
            p.1,
            q.0,
            q.1,
            w.thickness * SCALE
        );
    }

    for part in layout.on_level(level) {
        let PartKind::Opening(o) = &part.kind else {
            continue;
        };
        let t = layout
            .host_wall(level, o.at)
            .map_or(layout.style.wall_thickness, |(_, w)| w.thickness);
        let along = [o.facing[1], -o.facing[0]];
        let end = |k: f64| view.point([o.at[0] + along[0] * k, o.at[1] + along[1] * k]);
        let (p, q) = (end(-o.width / 2.0), end(o.width / 2.0));
        let stroke = t * SCALE + 1.0;
        match o.kind {
            OpeningKind::Door | OpeningKind::Archway => {
                let _ = writeln!(
                    s,
                    r#"<line x1="{:.1}" y1="{:.1}" x2="{:.1}" y2="{:.1}" stroke="{PAPER}" stroke-width="{stroke:.1}"/>"#,
                    p.0, p.1, q.0, q.1
                );
            }
            _ => {
                let _ = writeln!(
                    s,
                    r##"<line x1="{:.1}" y1="{:.1}" x2="{:.1}" y2="{:.1}" stroke="#DCEFF7" stroke-width="{:.1}"/>"##,
                    p.0,
                    p.1,
                    q.0,
                    q.1,
                    stroke - 2.0
                );
                let _ = writeln!(
                    s,
                    r#"<line x1="{:.1}" y1="{:.1}" x2="{:.1}" y2="{:.1}" stroke="{INK}" stroke-width="1"/>"#,
                    p.0, p.1, q.0, q.1
                );
            }
        }
    }

    if level == 0 {
        for part in layout.on_level(0) {
            let PartKind::Prop(p) = &part.kind else {
                continue;
            };
            prop(&mut s, &view, p);
        }
    }

    for part in layout.on_level(level) {
        let PartKind::Floor(f) = &part.kind else {
            continue;
        };
        let Some(room) = f.room else { continue };
        let (cx, cz) = f.rect.center();
        let (x, y) = view.point([cx, cz]);
        let size = if f.rect.min_side() < 2.2 { 9 } else { 12 };
        let _ = writeln!(
            s,
            r#"<text x="{x:.1}" y="{y:.1}" font-size="{size}" text-anchor="middle" fill="{INK}">{}</text>"#,
            room.label()
        );
        let _ = writeln!(
            s,
            r##"<text x="{x:.1}" y="{:.1}" font-size="{}" text-anchor="middle" fill="#7A6F60">{:.1} m²</text>"##,
            y + size as f64 + 2.0,
            size - 2,
            f.rect.area()
        );
    }

    let (nx, ny) = (width - PAD - 10.0, HEADER - 30.0);
    let _ = writeln!(
        s,
        r#"<path d="M {nx:.1} {:.1} L {:.1} {:.1} L {nx:.1} {:.1} L {:.1} {:.1} Z" fill="{INK}"/>"#,
        ny - 14.0,
        nx + 7.0,
        ny + 8.0,
        ny + 3.0,
        nx - 7.0,
        ny + 8.0
    );
    let _ = writeln!(
        s,
        r#"<text x="{nx:.1}" y="{:.1}" font-size="11" text-anchor="middle" fill="{INK}">N</text>"#,
        ny + 22.0
    );
    let bar_y = height - FOOTER / 2.0;
    let _ = writeln!(
        s,
        r#"<line x1="{PAD}" y1="{bar_y:.1}" x2="{:.1}" y2="{bar_y:.1}" stroke="{INK}" stroke-width="3"/>"#,
        PAD + 5.0 * SCALE
    );
    let _ = writeln!(
        s,
        r#"<text x="{:.1}" y="{:.1}" font-size="11" fill="{INK}">5 m</text>"#,
        PAD + 5.0 * SCALE + 8.0,
        bar_y + 4.0
    );
    let _ = writeln!(
        s,
        r##"<text x="{:.1}" y="{:.1}" font-size="10" text-anchor="end" fill="#7A6F60">Urbanitas · Noj Suon</text>"##,
        width - PAD,
        bar_y + 4.0
    );
    s.push_str("</svg>\n");
    s
}

struct View {
    min_x: f64,
    max_z: f64,
}

impl View {
    fn point(&self, p: P2) -> (f64, f64) {
        (
            PAD + (p[0] - self.min_x) * SCALE,
            HEADER + PAD + (self.max_z - p[1]) * SCALE,
        )
    }

    fn rect(&self, r: &Rect) -> (f64, f64, f64, f64) {
        let (x, y) = self.point([r.x, r.z1()]);
        (x, y, r.w * SCALE, r.d * SCALE)
    }
}

fn polygon(points: &[(f64, f64)]) -> String {
    points
        .iter()
        .map(|(x, y)| format!("{x:.1},{y:.1}"))
        .collect::<Vec<_>>()
        .join(" ")
}

fn stairs(s: &mut String, view: &View, st: &StairsPart) {
    let r = st.rect;
    let (x, y, w, h) = view.rect(&r);
    let _ = writeln!(
        s,
        r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#D9D2C5"/>"##
    );
    let along_z = matches!(st.heading, Heading::North | Heading::South);
    let run = if along_z { r.d } else { r.w };
    let treads = (run / 0.28).floor() as usize;
    for i in 1..treads {
        let t = run * i as f64 / treads as f64;
        let (p, q) = if along_z {
            (view.point([r.x, r.z + t]), view.point([r.x1(), r.z + t]))
        } else {
            (view.point([r.x + t, r.z]), view.point([r.x + t, r.z1()]))
        };
        let _ = writeln!(
            s,
            r##"<line x1="{:.1}" y1="{:.1}" x2="{:.1}" y2="{:.1}" stroke="#A89D8C" stroke-width="1"/>"##,
            p.0, p.1, q.0, q.1
        );
    }
}

fn area(s: &mut String, view: &View, a: &AreaPart) {
    let (x, y, w, h) = view.rect(&a.rect);
    let _ = match a.kind {
        AreaKind::Lawn => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#C9D39A" stroke="#9AAE6B"/>"##
        ),
        AreaKind::Path | AreaKind::Terrace => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#E3D6BC" stroke="#C9B48F"/>"##
        ),
        AreaKind::Pool => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" rx="4" fill="#8FCBE0" stroke="#C9B48F" stroke-width="5"/>"##
        ),
        AreaKind::Pergola => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="none" stroke="#7A5230" stroke-width="2" stroke-dasharray="3 3"/>"##
        ),
        AreaKind::Loggia => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#EBD9C4" stroke="#9A9C96" stroke-width="4"/>"##
        ),
        AreaKind::Hedge | AreaKind::Parterre => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#4F7A35"/>"##
        ),
        AreaKind::Courtyard | AreaKind::Piazza => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#E6DCC8" stroke="#9A9C96" stroke-width="2"/>"##
        ),
        AreaKind::Street => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#8E8B86"/>"##
        ),
        AreaKind::Road => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#E8DFCB"/>"##
        ),
        AreaKind::Vineyard => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#B9C78A" stroke="#6E7F3E" stroke-dasharray="2 6"/>"##
        ),
        AreaKind::Tower => writeln!(
            s,
            r##"<rect x="{x:.1}" y="{y:.1}" width="{w:.1}" height="{h:.1}" fill="#3B342C"/>"##
        ),
        AreaKind::Platform => Ok(()),
    };
}

fn prop(s: &mut String, view: &View, p: &PropPart) {
    let (x, y) = view.point(p.at);
    let r = p.kind.base_size() * p.scale * SCALE / 2.0;
    let _ = match p.kind {
        PropKind::OliveTree => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{r:.1}" fill="#9AA77A" fill-opacity="0.85" stroke="#6F7D52"/>"##
        ),
        PropKind::CypressTree => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{r:.1}" fill="#3E5E36" stroke="#2F4F2A"/>"##
        ),
        PropKind::LemonTree => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{r:.1}" fill="#6E9A45" stroke="#4F7A35"/><circle cx="{:.1}" cy="{:.1}" r="2.5" fill="#F2D33B"/>"##,
            x + r * 0.3,
            y - r * 0.2
        ),
        PropKind::Pot => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{r:.1}" fill="#C0693F"/>"##
        ),
        PropKind::Fountain => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{r:.1}" fill="#8FCBE0" stroke="#9A9C96" stroke-width="4"/>"##
        ),
        PropKind::Bench => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{:.1}" fill="#C9B48F"/>"##,
            r * 0.5
        ),
        PropKind::StonePine | PropKind::Palm => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{r:.1}" fill="#5E7A45" fill-opacity="0.8" stroke="#3E5A30"/>"##
        ),
        PropKind::Column | PropKind::Lamp | PropKind::Well | PropKind::Urn => writeln!(
            s,
            r##"<circle cx="{x:.1}" cy="{y:.1}" r="{r:.1}" fill="#9A9C96"/>"##
        ),
    };
}

fn room_color(room: Option<RoomKind>) -> &'static str {
    match room {
        Some(RoomKind::Living) => "#F3D9B1",
        Some(RoomKind::Lounge) => "#F0CFA0",
        Some(RoomKind::Kitchen) => "#F6E7A8",
        Some(RoomKind::Dining) => "#F2DDB8",
        Some(RoomKind::Bedroom) => "#CFE0EE",
        Some(RoomKind::Bathroom) => "#BFE3E0",
        Some(RoomKind::Study) => "#DCD3EC",
        Some(RoomKind::Hall) => "#E8E1D6",
        Some(RoomKind::Stairs) => "#D9D2C5",
        Some(RoomKind::Retail) => "#F4C7A1",
        Some(RoomKind::Storage) => "#DDD6CB",
        Some(RoomKind::Office) => "#D7E4C9",
        None => "#EFE7DA",
    }
}

fn esc(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}
