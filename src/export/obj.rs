//! Wavefront OBJ + MTL export.
//!
//! Units are metres. `y` is up, `x` runs west → east and `z` runs from the
//! street front (south) to the back (north). Every part of the building is
//! its own named group (`floor1_walls`, `roof_tiles`, `garden_olive_3`, …) so
//! it can be selected or hidden separately after import.

use std::f64::consts::{FRAC_PI_2, PI};
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::Path;

use crate::geometry::{Axis, Rect, Side};
use crate::model::*;
use crate::style::{Color, Palette};

const ARCH_SEGMENTS: usize = 8;
const STAIR_RISER: f64 = 0.19;

/// The text of an `.obj` file and the `.mtl` file it references.
pub struct ObjExport {
    pub obj: String,
    pub mtl: String,
}

/// Builds the mesh. `mtl_name` is the material file name written into the OBJ's `mtllib` line.
pub fn to_obj(building: &Building, mtl_name: &str) -> ObjExport {
    let mut mesh = Mesh::default();
    ground(&mut mesh, building);
    for floor in &building.floors {
        slab(&mut mesh, building, floor);
        exterior(&mut mesh, building, floor);
        interior(&mut mesh, building, floor);
        stairs(&mut mesh, building, floor);
    }
    roof(&mut mesh, building);
    ObjExport {
        obj: mesh.to_obj(&building.name, mtl_name),
        mtl: materials(&building.palette),
    }
}

/// Writes `path` and a matching `.mtl` file next to it.
pub fn write_obj(building: &Building, path: &Path) -> io::Result<()> {
    let mtl_path = path.with_extension("mtl");
    let mtl_name = mtl_path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("urbanitas.mtl");
    let export = to_obj(building, mtl_name);
    fs::write(path, export.obj)?;
    fs::write(&mtl_path, export.mtl)
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mat {
    Wall,
    InteriorWall,
    Trim,
    Wood,
    Glass,
    RoofTile,
    Slab,
    Stone,
    Iron,
    Lawn,
    Water,
    Foliage,
    OliveLeaf,
    CypressLeaf,
    Terracotta,
}

impl Mat {
    const ALL: [Mat; 15] = [
        Mat::Wall,
        Mat::InteriorWall,
        Mat::Trim,
        Mat::Wood,
        Mat::Glass,
        Mat::RoofTile,
        Mat::Slab,
        Mat::Stone,
        Mat::Iron,
        Mat::Lawn,
        Mat::Water,
        Mat::Foliage,
        Mat::OliveLeaf,
        Mat::CypressLeaf,
        Mat::Terracotta,
    ];

    fn name(self) -> &'static str {
        match self {
            Mat::Wall => "wall",
            Mat::InteriorWall => "interior_wall",
            Mat::Trim => "trim",
            Mat::Wood => "wood",
            Mat::Glass => "glass",
            Mat::RoofTile => "roof_tile",
            Mat::Slab => "slab",
            Mat::Stone => "stone",
            Mat::Iron => "iron",
            Mat::Lawn => "lawn",
            Mat::Water => "water",
            Mat::Foliage => "foliage",
            Mat::OliveLeaf => "olive_leaf",
            Mat::CypressLeaf => "cypress_leaf",
            Mat::Terracotta => "terracotta",
        }
    }

    fn color(self, palette: &Palette) -> Color {
        match self {
            Mat::Wall => palette.walls,
            Mat::InteriorWall => Color(0xF2, 0xEE, 0xE6),
            Mat::Trim => palette.trim,
            Mat::Wood => Color(0x7A, 0x52, 0x30),
            Mat::Glass => Color(0x9F, 0xC6, 0xD9),
            Mat::RoofTile => palette.roof,
            Mat::Slab => Color(0xE4, 0xDC, 0xCF),
            Mat::Stone => palette.stone,
            Mat::Iron => Color(0x2B, 0x2B, 0x2B),
            Mat::Lawn => Color(0x7C, 0x8F, 0x45),
            Mat::Water => Color(0x3F, 0xA7, 0xC9),
            Mat::Foliage => Color(0x4F, 0x7A, 0x35),
            Mat::OliveLeaf => Color(0x8A, 0x9A, 0x6B),
            Mat::CypressLeaf => Color(0x2F, 0x4F, 0x2A),
            Mat::Terracotta => Color(0xC0, 0x69, 0x3F),
        }
    }
}

fn materials(palette: &Palette) -> String {
    let mut out = String::from("# Urbanitas materials\n# Generated by Urbanitas (Noj Suon)\n");
    for mat in Mat::ALL {
        let [r, g, b] = mat.color(palette).rgb();
        let _ = writeln!(out, "\nnewmtl {}", mat.name());
        let _ = writeln!(
            out,
            "Ka 0.000 0.000 0.000\nKd {r:.3} {g:.3} {b:.3}\nKs 0.050 0.050 0.050\nNs 10\nillum 2"
        );
        match mat {
            Mat::Glass => out.push_str("d 0.45\nTr 0.55\n"),
            Mat::Water => out.push_str("d 0.80\nTr 0.20\n"),
            _ => {}
        }
    }
    out
}

/// Box faces, wound counter-clockwise when seen from outside.
const BOX_FACES: [[usize; 4]; 6] = [
    [0, 3, 2, 1],
    [4, 5, 6, 7],
    [0, 1, 5, 4],
    [3, 7, 6, 2],
    [0, 4, 7, 3],
    [1, 2, 6, 5],
];

#[derive(Default)]
struct Mesh {
    vertices: Vec<[f64; 3]>,
    groups: Vec<Group>,
}

struct Group {
    name: String,
    material: Mat,
    faces: Vec<Vec<usize>>,
}

impl Mesh {
    fn begin(&mut self, name: impl Into<String>, material: Mat) {
        self.groups.push(Group {
            name: name.into(),
            material,
            faces: Vec::new(),
        });
    }

    fn faces(&mut self) -> &mut Vec<Vec<usize>> {
        &mut self
            .groups
            .last_mut()
            .expect("call Mesh::begin before adding geometry")
            .faces
    }

    fn face(&mut self, points: &[[f64; 3]]) {
        let base = self.vertices.len();
        self.vertices.extend_from_slice(points);
        self.faces().push((base..base + points.len()).collect());
    }

    /// An axis-aligned box between two corners. Empty boxes are skipped.
    fn add_box(&mut self, a: [f64; 3], b: [f64; 3]) {
        let (lo, hi) = (min3(a, b), max3(a, b));
        if (0..3).any(|i| hi[i] - lo[i] <= 1e-6) {
            return;
        }
        let [x0, y0, z0] = lo;
        let [x1, y1, z1] = hi;
        let base = self.vertices.len();
        self.vertices.extend_from_slice(&[
            [x0, y0, z0],
            [x1, y0, z0],
            [x1, y1, z0],
            [x0, y1, z0],
            [x0, y0, z1],
            [x1, y0, z1],
            [x1, y1, z1],
            [x0, y1, z1],
        ]);
        let faces = self.faces();
        for face in BOX_FACES {
            faces.push(face.iter().map(|i| base + i).collect());
        }
    }

    /// A box over a ground-plane rectangle, from height `y0` to `y1`.
    fn add_prism(&mut self, rect: &Rect, y0: f64, y1: f64) {
        self.add_box([rect.x, y0, rect.z], [rect.x1(), y1, rect.z1()]);
    }

    fn to_obj(&self, name: &str, mtl_name: &str) -> String {
        let mut out = String::with_capacity(self.vertices.len() * 32);
        out.push_str("# Urbanitas procedural building\n# Generated by Urbanitas (Noj Suon)\n");
        let _ = writeln!(out, "mtllib {mtl_name}\no {name}");
        for [x, y, z] in &self.vertices {
            let _ = writeln!(out, "v {x:.4} {y:.4} {z:.4}");
        }
        for group in self.groups.iter().filter(|g| !g.faces.is_empty()) {
            let _ = writeln!(out, "g {}\nusemtl {}", group.name, group.material.name());
            for face in &group.faces {
                out.push('f');
                for index in face {
                    let _ = write!(out, " {}", index + 1);
                }
                out.push('\n');
            }
        }
        out
    }
}

fn min3(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [a[0].min(b[0]), a[1].min(b[1]), a[2].min(b[2])]
}

fn max3(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [a[0].max(b[0]), a[1].max(b[1]), a[2].max(b[2])]
}

/// Local coordinates on a straight wall: `u` along it, `v` up, `n` across its thickness.
#[derive(Clone, Copy)]
struct WallFrame {
    axis: Axis,
    /// Position of the wall's centre line on the other axis.
    coord: f64,
}

impl WallFrame {
    fn point(&self, u: f64, v: f64, n: f64) -> [f64; 3] {
        match self.axis {
            Axis::X => [u, v, self.coord + n],
            Axis::Z => [self.coord + n, v, u],
        }
    }

    /// A box spanning `u0..u1` and `v0..v1`; nothing when either range is empty.
    /// `n0` and `n1` may come in either order.
    #[allow(clippy::too_many_arguments)]
    fn add_box(&self, mesh: &mut Mesh, u0: f64, u1: f64, v0: f64, v1: f64, n0: f64, n1: f64) {
        if u1 <= u0 || v1 <= v0 {
            return;
        }
        mesh.add_box(self.point(u0, v0, n0), self.point(u1, v1, n1));
    }
}

/// A hole through a wall, in the wall's `u`/`v` coordinates.
struct Hole {
    u0: f64,
    u1: f64,
    v0: f64,
    v1: f64,
    arched: bool,
}

impl Hole {
    /// Where an arched top springs from; the plain top otherwise.
    fn rect_top(&self) -> f64 {
        if self.arched {
            self.v1 - (self.u1 - self.u0) / 2.0
        } else {
            self.v1
        }
    }
}

/// A solid wall from `start` to `end` with rectangular or arched holes cut out of it.
#[allow(clippy::too_many_arguments)]
fn wall_with_holes(
    mesh: &mut Mesh,
    frame: WallFrame,
    start: f64,
    end: f64,
    y0: f64,
    y1: f64,
    thickness: f64,
    holes: &mut [Hole],
) {
    holes.sort_by(|a, b| a.u0.total_cmp(&b.u0));
    let (n0, n1) = (-thickness / 2.0, thickness / 2.0);
    let mut cursor = start;
    for hole in holes.iter() {
        frame.add_box(mesh, cursor, hole.u0, y0, y1, n0, n1);
        frame.add_box(mesh, hole.u0, hole.u1, y0, hole.v0, n0, n1);
        frame.add_box(mesh, hole.u0, hole.u1, hole.v1, y1, n0, n1);
        if hole.arched {
            arch_spandrels(mesh, frame, hole, n0, n1);
        }
        cursor = hole.u1;
    }
    frame.add_box(mesh, cursor, end, y0, y1, n0, n1);
}

/// Fills the two corners above a round arch, so the hole reads as an arch.
fn arch_spandrels(mesh: &mut Mesh, frame: WallFrame, hole: &Hole, n0: f64, n1: f64) {
    let radius = (hole.u1 - hole.u0) / 2.0;
    let center = hole.u0 + radius;
    let spring = hole.v1 - radius;
    for (corner, from, to) in [(hole.u0, PI, FRAC_PI_2), (hole.u1, FRAC_PI_2, 0.0)] {
        let arc: Vec<(f64, f64)> = (0..=ARCH_SEGMENTS)
            .map(|i| {
                let angle = from + (to - from) * i as f64 / ARCH_SEGMENTS as f64;
                (center + radius * angle.cos(), spring + radius * angle.sin())
            })
            .collect();
        for pair in arc.windows(2) {
            let ((pu, pv), (qu, qv)) = (pair[0], pair[1]);
            mesh.face(&[
                frame.point(corner, hole.v1, n0),
                frame.point(pu, pv, n0),
                frame.point(qu, qv, n0),
            ]);
            mesh.face(&[
                frame.point(corner, hole.v1, n1),
                frame.point(qu, qv, n1),
                frame.point(pu, pv, n1),
            ]);
            mesh.face(&[
                frame.point(pu, pv, n0),
                frame.point(pu, pv, n1),
                frame.point(qu, qv, n1),
                frame.point(qu, qv, n0),
            ]);
        }
    }
}

/// The frame of an exterior wall; its outside is at `n = side.outward() * thickness / 2`.
fn side_frame(side: Side, footprint: &Rect, thickness: f64) -> WallFrame {
    let half = thickness / 2.0;
    match side {
        Side::South => WallFrame {
            axis: Axis::X,
            coord: footprint.z + half,
        },
        Side::North => WallFrame {
            axis: Axis::X,
            coord: footprint.z1() - half,
        },
        Side::West => WallFrame {
            axis: Axis::Z,
            coord: footprint.x + half,
        },
        Side::East => WallFrame {
            axis: Axis::Z,
            coord: footprint.x1() - half,
        },
    }
}

/// South and north walls run the full width; west and east walls fit between them.
fn side_range(side: Side, footprint: &Rect, thickness: f64) -> (f64, f64) {
    match side {
        Side::South | Side::North => (footprint.x, footprint.x1()),
        Side::West | Side::East => (footprint.z + thickness, footprint.z1() - thickness),
    }
}

fn ground(mesh: &mut Mesh, b: &Building) {
    let Some(garden) = &b.garden else {
        mesh.begin("ground_plinth", Mat::Stone);
        mesh.add_prism(&b.footprint.grow(1.0), -0.1, 0.02);
        return;
    };
    mesh.begin("ground_lawn", Mat::Lawn);
    mesh.add_prism(&garden.lot, -0.1, 0.0);
    for (i, feature) in garden.features.iter().enumerate() {
        let name = format!("garden_{}_{i}", feature.kind.label());
        let r = feature.rect;
        let (cx, cz) = r.center();
        match feature.kind {
            FeatureKind::Path | FeatureKind::Terrace => {
                mesh.begin(name, Mat::Stone);
                mesh.add_prism(&r, 0.0, feature.height);
            }
            FeatureKind::Pool => {
                mesh.begin(format!("{name}_water"), Mat::Water);
                mesh.add_prism(&r, -0.1, 0.01);
                mesh.begin(format!("{name}_coping"), Mat::Stone);
                for part in r.grow(0.3).subtract(&r) {
                    mesh.add_prism(&part, 0.0, 0.06);
                }
            }
            FeatureKind::Pergola => {
                mesh.begin(name, Mat::Wood);
                let (post, h) = (0.15, feature.height);
                for (x, z) in [
                    (r.x, r.z),
                    (r.x1() - post, r.z),
                    (r.x, r.z1() - post),
                    (r.x1() - post, r.z1() - post),
                ] {
                    mesh.add_box([x, 0.0, z], [x + post, h, z + post]);
                }
                mesh.add_box([r.x, h - 0.2, r.z], [r.x1(), h, r.z + post]);
                mesh.add_box([r.x, h - 0.2, r.z1() - post], [r.x1(), h, r.z1()]);
                let slats = (r.w / 0.45).floor() as usize;
                for s in 0..=slats {
                    let x = r.x + (r.w - 0.08) * s as f64 / slats.max(1) as f64;
                    mesh.add_box([x, h, r.z - 0.1], [x + 0.08, h + 0.12, r.z1() + 0.1]);
                }
            }
            FeatureKind::OliveTree | FeatureKind::LemonTree => {
                let olive = feature.kind == FeatureKind::OliveTree;
                let trunk = if olive { 0.3 } else { 0.2 };
                let trunk_h = feature.height * 0.35;
                mesh.begin(format!("{name}_trunk"), Mat::Wood);
                mesh.add_box(
                    [cx - trunk / 2.0, 0.0, cz - trunk / 2.0],
                    [cx + trunk / 2.0, trunk_h, cz + trunk / 2.0],
                );
                mesh.begin(
                    format!("{name}_canopy"),
                    if olive { Mat::OliveLeaf } else { Mat::Foliage },
                );
                mesh.add_prism(&r, trunk_h, feature.height * 0.8);
                mesh.add_prism(&r.grow(-r.w * 0.2), feature.height * 0.8, feature.height);
            }
            FeatureKind::CypressTree => {
                mesh.begin(format!("{name}_trunk"), Mat::Wood);
                mesh.add_box([cx - 0.1, 0.0, cz - 0.1], [cx + 0.1, 0.6, cz + 0.1]);
                mesh.begin(format!("{name}_canopy"), Mat::CypressLeaf);
                // Three tapering tiers: (width scale, bottom, top) as fractions of the canopy.
                let span = feature.height - 0.6;
                for (scale, from, to) in [(1.0, 0.0, 0.45), (0.75, 0.45, 0.75), (0.45, 0.75, 1.0)] {
                    mesh.add_prism(
                        &r.grow(-r.w * (1.0 - scale) / 2.0),
                        0.6 + span * from,
                        0.6 + span * to,
                    );
                }
            }
            FeatureKind::Pot => {
                mesh.begin(name, Mat::Terracotta);
                mesh.add_prism(&r, 0.0, feature.height);
                mesh.begin(format!("garden_pot_plant_{i}"), Mat::Foliage);
                mesh.add_prism(&r.grow(-0.05), feature.height, feature.height + 0.35);
            }
        }
    }
}

fn slab(mesh: &mut Mesh, b: &Building, floor: &Floor) {
    mesh.begin(format!("floor{}_slab", floor.level), Mat::Slab);
    let y0 = floor.elevation;
    let y1 = y0 + b.style.slab_thickness;
    let parts = match b.stairs() {
        Some(stairs) if floor.level > 0 => b.footprint.subtract(&stairs),
        _ => vec![b.footprint],
    };
    // Tuck the slab edges into the walls so they don't show through the facade.
    let inner = b.footprint.grow(-b.style.wall_thickness / 2.0);
    for part in parts.iter().filter_map(|p| p.intersection(&inner)) {
        mesh.add_prism(&part, y0, y1);
    }
}

fn exterior(mesh: &mut Mesh, b: &Building, floor: &Floor) {
    let style = &b.style;
    let t = style.wall_thickness;
    let y0 = floor.elevation;
    // The top floor's walls also wrap the roof slab's edge.
    let is_top = floor.level as usize + 1 == b.floors.len();
    let y1 = y0 + floor.height + if is_top { style.slab_thickness } else { 0.0 };
    let level = floor.level;

    mesh.begin(format!("floor{level}_walls"), Mat::Wall);
    for side in Side::ALL {
        let frame = side_frame(side, &b.footprint, t);
        let (start, end) = side_range(side, &b.footprint, t);
        let mut holes: Vec<Hole> = floor
            .openings
            .iter()
            .filter(|o| o.side == side)
            .map(|o| Hole {
                u0: o.start(),
                u1: o.end(),
                v0: y0 + o.sill,
                v1: y0 + o.sill + o.height,
                arched: o.arched,
            })
            .collect();
        wall_with_holes(mesh, frame, start, end, y0, y1, t, &mut holes);
    }

    let openings: Vec<(&Opening, WallFrame, Hole)> = floor
        .openings
        .iter()
        .map(|o| {
            let hole = Hole {
                u0: o.start(),
                u1: o.end(),
                v0: y0 + o.sill,
                v1: y0 + o.sill + o.height,
                arched: o.arched,
            };
            (o, side_frame(o.side, &b.footprint, t), hole)
        })
        .collect();

    mesh.begin(format!("floor{level}_glass"), Mat::Glass);
    for (_, frame, hole) in openings.iter().filter(|(o, ..)| o.is_glazed()) {
        frame.add_box(
            mesh,
            hole.u0,
            hole.u1,
            hole.v0,
            hole.rect_top(),
            -0.02,
            0.02,
        );
    }

    mesh.begin(format!("floor{level}_doors"), Mat::Trim);
    for (_, frame, hole) in openings
        .iter()
        .filter(|(o, ..)| o.kind == OpeningKind::Door)
    {
        frame.add_box(
            mesh,
            hole.u0,
            hole.u1,
            hole.v0,
            hole.rect_top(),
            -0.04,
            0.04,
        );
    }

    mesh.begin(format!("floor{level}_sills"), Mat::Stone);
    for (o, frame, hole) in openings
        .iter()
        .filter(|(o, ..)| o.kind == OpeningKind::Window)
    {
        let out = o.side.outward();
        frame.add_box(
            mesh,
            hole.u0 - 0.08,
            hole.u1 + 0.08,
            hole.v0 - 0.06,
            hole.v0,
            out * (t / 2.0 - 0.05),
            out * (t / 2.0 + 0.08),
        );
    }

    if style.shutters {
        mesh.begin(format!("floor{level}_shutters"), Mat::Trim);
        for (o, frame, hole) in openings
            .iter()
            .filter(|(o, ..)| o.kind == OpeningKind::Window && o.width >= style.window.width)
        {
            let out = o.side.outward();
            let (n0, n1) = (out * t / 2.0, out * (t / 2.0 + 0.05));
            let half = o.width / 2.0;
            frame.add_box(
                mesh,
                hole.u0 - half,
                hole.u0,
                hole.v0,
                hole.rect_top(),
                n0,
                n1,
            );
            frame.add_box(
                mesh,
                hole.u1,
                hole.u1 + half,
                hole.v0,
                hole.rect_top(),
                n0,
                n1,
            );
        }
    }

    for (i, balcony) in floor.balconies.iter().enumerate() {
        let frame = side_frame(balcony.side, &b.footprint, t);
        let out = balcony.side.outward();
        let face = out * t / 2.0;
        let edge = face + out * balcony.depth;
        let (u0, u1) = (
            balcony.center - balcony.width / 2.0,
            balcony.center + balcony.width / 2.0,
        );
        let top = y0 + style.slab_thickness;
        mesh.begin(format!("floor{level}_balcony{i}"), Mat::Stone);
        frame.add_box(mesh, u0, u1, y0, top, face, edge);
        mesh.begin(format!("floor{level}_balcony{i}_railing"), Mat::Iron);
        let rail = 1.0;
        let bar = 0.03;
        frame.add_box(
            mesh,
            u0,
            u1,
            top + rail - 0.05,
            top + rail,
            edge - out * 0.05,
            edge,
        );
        for u in [u0, u1 - 0.05] {
            frame.add_box(mesh, u, u + 0.05, top + rail - 0.05, top + rail, face, edge);
        }
        let posts = ((u1 - u0) / 0.15).floor() as usize;
        for p in 0..=posts {
            let u = u0 + (u1 - u0 - bar) * p as f64 / posts.max(1) as f64;
            frame.add_box(mesh, u, u + bar, top, top + rail, edge - out * bar, edge);
        }
        let side_posts = (balcony.depth / 0.15).floor() as usize;
        for p in 1..side_posts {
            let n = face + out * balcony.depth * p as f64 / side_posts as f64;
            for u in [u0, u1 - bar] {
                frame.add_box(mesh, u, u + bar, top, top + rail, n, n + out * bar);
            }
        }
    }
}

fn interior(mesh: &mut Mesh, b: &Building, floor: &Floor) {
    let style = &b.style;
    mesh.begin(
        format!("floor{}_partitions", floor.level),
        Mat::InteriorWall,
    );
    let y0 = floor.elevation + style.slab_thickness;
    let y1 = floor.elevation + floor.height;
    for wall in &floor.walls {
        let seg = wall
            .segment
            .inside_walls(&b.footprint, style.wall_thickness);
        let frame = WallFrame {
            axis: seg.axis,
            coord: seg.coord,
        };
        let mut holes: Vec<Hole> = wall
            .door
            .iter()
            .map(|d| Hole {
                u0: d.center - d.width / 2.0,
                u1: d.center + d.width / 2.0,
                v0: y0,
                v1: y0 + d.height,
                arched: d.arched,
            })
            .collect();
        wall_with_holes(
            mesh,
            frame,
            seg.start,
            seg.end,
            y0,
            y1,
            style.partition_thickness,
            &mut holes,
        );
    }
}

/// A straight flight up to the next floor, in the stair well of every floor but the top one.
fn stairs(mesh: &mut Mesh, b: &Building, floor: &Floor) {
    if floor.level as usize + 1 >= b.floors.len() {
        return;
    }
    let Some(well) = floor.find(RoomKind::Stairs).map(|r| r.rect) else {
        return;
    };
    let style = &b.style;
    mesh.begin(format!("floor{}_stairs", floor.level), Mat::Stone);
    let steps = (floor.height / STAIR_RISER).ceil() as usize;
    let riser = floor.height / steps as f64;
    let start = well.z + 0.4;
    let run = (well.d - 0.7) / steps as f64;
    let x0 = well.x + style.wall_thickness + 0.05;
    let x1 = well.x1() - style.partition_thickness / 2.0 - 0.05;
    let base = floor.elevation + style.slab_thickness;
    for i in 0..steps {
        let z = start + run * i as f64;
        mesh.add_box(
            [x0, base, z],
            [
                x1,
                floor.elevation + riser * (i + 1) as f64 + style.slab_thickness,
                z + run,
            ],
        );
    }
}

fn roof(mesh: &mut Mesh, b: &Building) {
    let fp = b.footprint;
    let style = &b.style;
    let top = b.floors.len() as f64 * style.floor_height;
    let y = top + style.slab_thickness;
    mesh.begin("roof_slab", Mat::Slab);
    mesh.add_prism(&fp.grow(-style.wall_thickness / 2.0), top, y);
    match b.roof {
        Roof::Flat { parapet_height } => {
            mesh.begin("roof_parapet", Mat::Wall);
            let t = 0.25;
            let h = y + parapet_height;
            mesh.add_box([fp.x, y, fp.z], [fp.x1(), h, fp.z + t]);
            mesh.add_box([fp.x, y, fp.z1() - t], [fp.x1(), h, fp.z1()]);
            mesh.add_box([fp.x, y, fp.z + t], [fp.x + t, h, fp.z1() - t]);
            mesh.add_box([fp.x1() - t, y, fp.z + t], [fp.x1(), h, fp.z1() - t]);
            mesh.begin("roof_coping", Mat::Stone);
            mesh.add_box(
                [fp.x - 0.03, h, fp.z - 0.03],
                [fp.x1() + 0.03, h + 0.05, fp.z + t + 0.03],
            );
            mesh.add_box(
                [fp.x - 0.03, h, fp.z1() - t - 0.03],
                [fp.x1() + 0.03, h + 0.05, fp.z1() + 0.03],
            );
            mesh.add_box(
                [fp.x - 0.03, h, fp.z + t + 0.03],
                [fp.x + t + 0.03, h + 0.05, fp.z1() - t - 0.03],
            );
            mesh.add_box(
                [fp.x1() - t - 0.03, h, fp.z + t + 0.03],
                [fp.x1() + 0.03, h + 0.05, fp.z1() - t - 0.03],
            );
        }
        Roof::Hip {
            overhang,
            ridge_height,
            ..
        } => {
            let e = fp.grow(overhang);
            let ry = y + ridge_height;
            mesh.begin("roof_tiles", Mat::RoofTile);
            if e.w >= e.d {
                let half = e.d / 2.0;
                let rz = e.z + half;
                let (rx0, rx1) = (e.x + half, e.x1() - half);
                mesh.face(&[
                    [e.x, y, e.z],
                    [rx0, ry, rz],
                    [rx1, ry, rz],
                    [e.x1(), y, e.z],
                ]);
                mesh.face(&[
                    [e.x1(), y, e.z1()],
                    [rx1, ry, rz],
                    [rx0, ry, rz],
                    [e.x, y, e.z1()],
                ]);
                mesh.face(&[[e.x, y, e.z1()], [rx0, ry, rz], [e.x, y, e.z]]);
                mesh.face(&[[e.x1(), y, e.z], [rx1, ry, rz], [e.x1(), y, e.z1()]]);
            } else {
                let half = e.w / 2.0;
                let rx = e.x + half;
                let (rz0, rz1) = (e.z + half, e.z1() - half);
                mesh.face(&[
                    [e.x, y, e.z1()],
                    [rx, ry, rz1],
                    [rx, ry, rz0],
                    [e.x, y, e.z],
                ]);
                mesh.face(&[
                    [e.x1(), y, e.z],
                    [rx, ry, rz0],
                    [rx, ry, rz1],
                    [e.x1(), y, e.z1()],
                ]);
                mesh.face(&[[e.x, y, e.z], [rx, ry, rz0], [e.x1(), y, e.z]]);
                mesh.face(&[[e.x1(), y, e.z1()], [rx, ry, rz1], [e.x, y, e.z1()]]);
            }
            mesh.begin("roof_soffit", Mat::Wood);
            mesh.face(&[
                [e.x, y, e.z],
                [e.x1(), y, e.z],
                [e.x1(), y, e.z1()],
                [e.x, y, e.z1()],
            ]);
        }
    }
}
