#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize, ValueEnum)]
#[serde(rename_all = "snake_case")]
pub enum Context {
    /// One building.
    #[default]
    Single,
    /// A street of attached palazzi and a piazza.
    Urban,
    /// Villas on walled plots along a lane.
    Suburban,
    /// A villa or farmhouse in the countryside.
    Rural,
}

impl Context {
    pub const ALL: [Context; 4] = [
        Context::Single,
        Context::Urban,
        Context::Suburban,
        Context::Rural,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Context::Single => "Single building",
            Context::Urban => "Urban (centro storico)",
            Context::Suburban => "Suburban villas",
            Context::Rural => "Rural (campagna)",
        }
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct SiteParams {
    pub context: Context,
    /// The building, for a single site; the style and seed for every site.
    pub building: BuildingParams,
    /// How many buildings an urban or suburban site gets.
    pub buildings: u32,
    /// Height of the hills, in metres.
    pub relief: f64,
}

impl Default for SiteParams {
    fn default() -> Self {
        Self {
            context: Context::Single,
            building: BuildingParams::default(),
            buildings: 6,
            relief: 0.0,
        }
    }
}

/// Builds the site as one layout.
pub fn generate_site(p: &SiteParams) -> Result<Layout, ParamError> {
    p.building.validate()?;
    let mut rng = Rng::new(p.building.seed ^ 0xC17E);
    let style = StyleProfile::for_style(p.building.style);
    let palette = Palette::choose(p.building.style, &mut Rng::new(p.building.seed));
    let mut site = Site {
        layout: Layout::new(
            format!("{}_{}", context_slug(p.context), p.building.seed),
            style,
            palette,
        ),
        rng: &mut rng,
    };
    match p.context {
        Context::Single => site.single(p)?,
        Context::Urban => site.urban(p)?,
        Context::Suburban => site.suburban(p)?,
        Context::Rural => site.rural(p)?,
    }
    site.layout.description = format!(
        "{} · {} · seed {} · {} building(s)",
        p.context.label(),
        p.building.style.label(),
        p.building.seed,
        site.layout.palettes.len().max(1)
    );
    Ok(site.layout)
}

fn context_slug(context: Context) -> &'static str {
    match context {
        Context::Single => "building",
        Context::Urban => "urban",
        Context::Suburban => "suburban",
        Context::Rural => "rural",
    }
}

struct Site<'r> {
    layout: Layout,
    rng: &'r mut Rng,
}

impl Site<'_> {
    /// Ground over the whole site, flat when `relief` is zero.
    fn terrain(&mut self, rect: Rect, relief: f64, slope: f64) {
        let spacing = (rect.w.max(rect.d) / 96.0).max(0.75);
        let seed = self.rng.next_u64();
        self.layout.terrain = Some(Terrain::generate(rect, spacing, relief, slope, seed));
    }

    /// Generates a building and places its footprint's south-west corner at `at`.
    /// `facing_north` turns it round to face a street on its north side.
    /// Returns the footprint as placed.
    fn building(
        &mut self,
        params: &BuildingParams,
        at: P2,
        facing_north: bool,
        plinth: bool,
    ) -> Result<Rect, ParamError> {
        let b = generate(params)?;
        let fp = Rect::new(at[0], at[1], b.footprint.w, b.footprint.d);
        let lot = b.garden.as_ref().map_or(fp, |g| {
            Rect::new(at[0] + g.lot.x, at[1] + g.lot.z, g.lot.w, g.lot.d)
        });
        let placed_lot = if facing_north {
            flip_rect(&lot, fp.center())
        } else {
            lot
        };
        let ground = match self.layout.terrain.as_mut() {
            Some(t) => {
                let (lo, hi) = t.range_in(&placed_lot);
                let level = if plinth { hi } else { (lo + hi) / 2.0 };
                t.flatten_pad(&placed_lot.grow(0.3), level, if plinth { 0.8 } else { 6.0 });
                level
            }
            None => 0.0,
        };
        let group = self.layout.new_group(b.palette.clone());
        let first = self.layout.parts.len();
        append_building(&mut self.layout, &b, at, ground, Some(group));
        if facing_north {
            let c = fp.center();
            for part in &mut self.layout.parts[first..] {
                part.rotate_half_about([c.0, c.1]);
            }
        }
        if plinth && self.layout.terrain.is_some() {
            self.layout.add_in(
                0,
                ground,
                Some(group),
                PartKind::Area(AreaPart {
                    kind: AreaKind::Platform,
                    rect: fp.grow(0.15),
                    height: 0.0,
                }),
            );
        }
        Ok(fp)
    }

    fn area(&mut self, kind: AreaKind, rect: Rect) {
        let ground = self.layout.ground_at(rect_centre(&rect));
        self.layout.add_in(
            0,
            ground,
            None,
            PartKind::Area(AreaPart {
                kind,
                rect,
                height: kind.default_height(),
            }),
        );
    }

    fn prop(&mut self, kind: PropKind, at: P2, scale: f64) {
        let ground = self.layout.ground_at(at);
        let height = kind.default_height() * scale.sqrt();
        self.layout.add_in(
            0,
            ground,
            None,
            PartKind::Prop(PropPart {
                kind,
                at,
                yaw: self.rng.range(0.0, std::f64::consts::TAU),
                scale,
                height,
            }),
        );
    }

    fn wall(&mut self, finish: WallFinish, a: P2, b: P2) {
        let ground = self
            .layout
            .ground_at([(a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0]);
        let wall = Wall {
            a,
            b,
            height: finish.default_height(),
            thickness: finish.default_thickness(),
            exterior: false,
            base: 0.0,
            finish,
        };
        self.layout.add_in(0, ground, None, PartKind::Wall(wall));
    }

    fn gate(&mut self, at: P2, facing: P2, width: f64, height: f64) {
        let ground = self.layout.ground_at(at);
        self.layout.add_in(
            0,
            ground,
            None,
            PartKind::Opening(OpeningPart {
                kind: OpeningKind::Gate,
                at,
                width,
                height,
                sill: 0.0,
                arched: false,
                facing,
            }),
        );
    }

    fn single(&mut self, p: &SiteParams) -> Result<(), ParamError> {
        let b = &p.building;
        if p.relief > 0.0 {
            let margin = 30.0;
            self.terrain(
                Rect::new(
                    -margin,
                    -margin,
                    b.size.width + 2.0 * margin,
                    b.size.depth + 2.0 * margin,
                ),
                p.relief,
                0.0,
            );
        }
        self.building(b, [0.0, 0.0], false, false)?;
        Ok(())
    }

    fn urban(&mut self, p: &SiteParams) -> Result<(), ParamError> {
        let total = p.buildings.clamp(2, 16) as usize;
        let north_count = total.div_ceil(2);
        let south_count = total - north_count;
        let street = 7.0;
        let half = street / 2.0;
        // Plot widths along each side of the street.
        let plots = |n: usize, rng: &mut Rng| {
            (0..n)
                .map(|_| (rng.range(9.0, 17.0) * 2.0).round() / 2.0)
                .collect::<Vec<f64>>()
        };
        let north = plots(north_count, self.rng);
        let mut south = plots(south_count, self.rng);
        let piazza_w = 22.0;
        let piazza_at = south.len() / 2;
        let length = north
            .iter()
            .sum::<f64>()
            .max(south.iter().sum::<f64>() + piazza_w)
            + 8.0;
        let depth = 22.0;
        let x0 = -length / 2.0;
        self.terrain(
            Rect::new(
                x0 - 15.0,
                -half - depth - 20.0,
                length + 30.0,
                street + 2.0 * depth + 40.0,
            ),
            p.relief * 0.4,
            0.0,
        );
        // A gentle climb along the street.
        if let Some(t) = self.layout.terrain.as_mut() {
            let rise = 0.04 * p.relief.max(1.0);
            for j in 0..=t.rows {
                for i in 0..=t.cols {
                    let x = t.point(i, j)[0];
                    t.heights[j * (t.cols + 1) + i] += (rise * (x - x0)) as f32;
                }
            }
        }

        let row = |site: &mut Self,
                   widths: &[f64],
                   facing_north: bool,
                   skip: Option<usize>|
         -> Result<(), ParamError> {
            let mut x = x0 + 4.0;
            for (i, &w) in widths.iter().enumerate() {
                if Some(i) == skip {
                    x += piazza_w;
                }
                let d = (site.rng.range(14.0, 20.0) * 2.0).round() / 2.0;
                let kind = *site.rng.pick(&[
                    BuildingType::Apartment,
                    BuildingType::Apartment,
                    BuildingType::Shop,
                    BuildingType::Villa,
                ]);
                let floors = 2 + site.rng.below(3) as u32;
                let rooms = ((w - 2.6) * d / 18.0).floor().clamp(2.0, 7.0) as u32;
                let params = BuildingParams {
                    seed: site.rng.next_u64() % 1_000_000,
                    floors,
                    size: Size { width: w, depth: d },
                    building_type: kind,
                    rooms,
                    garden: Garden::None,
                    style: p.building.style,
                    shape: if w >= 16.0 && d >= 16.0 {
                        Shape::Auto
                    } else {
                        Shape::Block
                    },
                };
                let z = if facing_north { -half - d } else { half };
                site.building(&params, [x, z], facing_north, true)?;
                x += w;
            }
            Ok(())
        };
        row(self, &north, false, None)?;
        south.truncate(south_count);
        row(self, &south, true, (south_count > 0).then_some(piazza_at))?;

        // The whole quarter is paved; the street runs through it in dark cobbles.
        self.area(
            AreaKind::Terrace,
            Rect::new(
                x0 - 4.0,
                -half - depth - 4.0,
                length + 8.0,
                street + 2.0 * depth + 8.0,
            ),
        );
        self.area(AreaKind::Street, Rect::new(x0, -half, length, street));
        // The piazza opens off the south side of the street.
        let px = x0 + 4.0 + south.iter().take(piazza_at).sum::<f64>();
        let piazza = Rect::new(px, -half - depth, piazza_w, depth);
        self.area(AreaKind::Piazza, piazza);
        let (cx, cz) = rect_centre_tuple(&piazza);
        self.prop(PropKind::Fountain, [cx, cz], 1.6);
        for dx in [-7.0, 7.0] {
            self.prop(PropKind::Bench, [cx + dx, cz + 4.0], 1.0);
            self.prop(PropKind::Lamp, [cx + dx, cz - 4.0], 1.0);
        }
        // Lanterns along the street.
        let mut x = x0 + 6.0;
        while x < x0 + length - 4.0 {
            self.prop(PropKind::Lamp, [x, half - 0.6], 1.0);
            x += 11.0;
        }
        Ok(())
    }

    fn suburban(&mut self, p: &SiteParams) -> Result<(), ParamError> {
        let count = p.buildings.clamp(1, 6) as usize;
        let plot_w = 30.0;
        let plot_d = 32.0;
        let lane = 6.0;
        let length = count as f64 * plot_w;
        let x0 = -length / 2.0;
        self.terrain(
            Rect::new(x0 - 25.0, -lane - 30.0, length + 50.0, plot_d + lane + 60.0),
            p.relief * 0.7,
            0.0,
        );
        self.area(
            AreaKind::Road,
            Rect::new(x0 - 10.0, -lane, length + 20.0, lane),
        );
        for i in 0..count {
            let px = x0 + i as f64 * plot_w;
            let w = (self.rng.range(12.0, 18.0) * 2.0).round() / 2.0;
            let d = (self.rng.range(10.0, 14.0) * 2.0).round() / 2.0;
            let params = BuildingParams {
                seed: self.rng.next_u64() % 1_000_000,
                floors: 1 + self.rng.below(2) as u32,
                size: Size { width: w, depth: d },
                building_type: if self.rng.chance(0.6) {
                    BuildingType::Villa
                } else {
                    BuildingType::House
                },
                rooms: 4 + self.rng.below(2) as u32,
                garden: Garden::Surrounding,
                style: p.building.style,
                shape: Shape::Auto,
            };
            // The villa sits back from the lane in the middle of its plot.
            let at = [px + (plot_w - w) / 2.0, 7.0];
            self.building(&params, at, false, false)?;
            // Garden walls round the plot, with a gate onto the lane in line with the front door.
            let plot = Rect::new(px + 0.5, 0.5, plot_w - 1.0, plot_d - 1.0);
            let door_x = self
                .layout
                .parts
                .iter()
                .rev()
                .find_map(|part| match &part.kind {
                    PartKind::Opening(o) if o.kind == OpeningKind::Door && o.facing[1] < 0.0 => {
                        Some(o.at[0])
                    }
                    _ => None,
                })
                .unwrap_or(px + plot_w / 2.0);
            let finish = if p.building.style == crate::params::ArchitectureStyle::Mediterranean {
                WallFinish::Garden
            } else {
                *self.rng.pick(&[WallFinish::Garden, WallFinish::Fence])
            };
            let corners = [
                [plot.x, plot.z],
                [plot.x1(), plot.z],
                [plot.x1(), plot.z1()],
                [plot.x, plot.z1()],
            ];
            for k in 0..4 {
                self.wall(finish, corners[k], corners[(k + 1) % 4]);
            }
            let gate_x = door_x.clamp(plot.x + 2.0, plot.x1() - 2.0);
            self.gate([gate_x, plot.z], [0.0, -1.0], 2.4, finish.default_height());
            self.prop(PropKind::CypressTree, [gate_x - 2.4, plot.z - 1.2], 1.0);
            self.prop(PropKind::CypressTree, [gate_x + 2.4, plot.z - 1.2], 1.0);
        }
        Ok(())
    }

    fn rural(&mut self, p: &SiteParams) -> Result<(), ParamError> {
        let size = 140.0;
        let area = Rect::new(-size / 2.0, -size / 2.0, size, size);
        self.terrain(area, p.relief.max(4.0), 0.0);
        let farmhouse = BuildingParams {
            size: Size {
                width: p.building.size.width.max(14.0),
                depth: p.building.size.depth.max(11.0),
            },
            garden: Garden::Surrounding,
            building_type: if self.rng.chance(0.5) {
                BuildingType::Villa
            } else {
                BuildingType::House
            },
            ..p.building.clone()
        };
        let fp = self.building(
            &farmhouse,
            [-farmhouse.size.width / 2.0, -farmhouse.size.depth / 2.0],
            false,
            false,
        )?;
        if p.buildings >= 2 {
            let barn = BuildingParams {
                seed: farmhouse.seed + 1,
                floors: 1,
                size: Size {
                    width: 10.0,
                    depth: 8.0,
                },
                building_type: BuildingType::House,
                rooms: 3,
                garden: Garden::None,
                shape: Shape::Block,
                ..farmhouse.clone()
            };
            self.building(&barn, [fp.x1() + 12.0, fp.z + 4.0], false, false)?;
        }

        // A white road up from the south edge, lined with cypresses.
        let road_x = fp.center().0 - 2.0;
        let road = Rect::new(road_x, area.z + 2.0, 4.0, fp.z - 7.0 - (area.z + 2.0));
        self.area(AreaKind::Road, road);
        let mut z = road.z + 3.0;
        while z < road.z1() - 2.0 {
            self.prop(PropKind::CypressTree, [road.x - 1.6, z], 1.1);
            self.prop(PropKind::CypressTree, [road.x1() + 1.6, z], 1.1);
            z += 6.5;
        }

        // An olive grove to the east and vineyard rows to the west, each walled in dry stone.
        let grove = Rect::new(fp.x1() + 10.0, area.z + 12.0, 40.0, 42.0);
        let mut x = grove.x + 3.0;
        while x < grove.x1() - 2.0 {
            let mut z = grove.z + 3.0;
            while z < grove.z1() - 2.0 {
                let j = self.rng.range(-0.8, 0.8);
                let scale = self.rng.range(0.85, 1.15);
                self.prop(PropKind::OliveTree, [x + j, z - j], scale);
                z += 7.0;
            }
            x += 7.0;
        }
        let vineyard = Rect::new(fp.x - 50.0, area.z + 14.0, 40.0, 36.0);
        self.area(AreaKind::Vineyard, vineyard);
        for field in [grove, vineyard] {
            let f = field.grow(1.0);
            self.wall(WallFinish::DryStone, [f.x, f.z], [f.x1(), f.z]);
            self.wall(WallFinish::DryStone, [f.x1(), f.z], [f.x1(), f.z1()]);
            self.wall(WallFinish::DryStone, [f.x, f.z1()], [f.x, f.z]);
        }
        // Stone pines and a few strays on the hillside.
        for _ in 0..10 {
            let at = [
                self.rng.range(area.x + 8.0, area.x1() - 8.0),
                self.rng.range(fp.z1() + 20.0, area.z1() - 8.0),
            ];
            let kind = if self.rng.chance(0.5) {
                PropKind::StonePine
            } else {
                PropKind::OliveTree
            };
            let scale = self.rng.range(0.8, 1.2);
            self.prop(kind, at, scale);
        }
        Ok(())
    }
}

fn rect_centre(r: &Rect) -> P2 {
    let (x, z) = r.center();
    [x, z]
}

fn rect_centre_tuple(r: &Rect) -> (f64, f64) {
    r.center()
}

fn flip_rect(r: &Rect, c: (f64, f64)) -> Rect {
    Rect::new(2.0 * c.0 - r.x1(), 2.0 * c.1 - r.z1(), r.w, r.d)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::params::ArchitectureStyle;

    fn site(context: Context, style: ArchitectureStyle, relief: f64) -> Layout {
        let p = SiteParams {
            context,
            building: BuildingParams {
                style,
                seed: 11,
                size: Size {
                    width: 16.0,
                    depth: 12.0,
                },
                rooms: 4,
                ..BuildingParams::default()
            },
            buildings: 6,
            relief,
        };
        generate_site(&p).unwrap()
    }

    #[test]
    fn sites_have_several_separate_buildings() {
        for context in [Context::Urban, Context::Suburban, Context::Rural] {
            for style in ArchitectureStyle::ALL {
                let layout = site(context, style, 3.0);
                let groups = layout.palettes.len();
                assert!(
                    groups >= if context == Context::Rural { 1 } else { 2 },
                    "{context:?}"
                );
                // Footprints of different buildings don't overlap.
                let footprint = |g: u32| {
                    layout
                        .group_parts(g)
                        .filter(|p| matches!(&p.kind, PartKind::Floor(_)))
                        .map(Part::footprint)
                        .collect::<Vec<_>>()
                };
                for a in 0..groups as u32 {
                    for b in a + 1..groups as u32 {
                        for ra in footprint(a) {
                            for rb in footprint(b) {
                                assert!(
                                    !ra.grow(-0.05).intersects(&rb.grow(-0.05)),
                                    "{context:?}: buildings {a} and {b} overlap"
                                );
                            }
                        }
                    }
                }
                // Every building stands level: all its parts share one ground height.
                for g in 0..groups as u32 {
                    let grounds: Vec<f64> = layout.group_parts(g).map(|p| p.ground).collect();
                    assert!(grounds.windows(2).all(|w| (w[0] - w[1]).abs() < 1e-9));
                }
                let back = Layout::from_json(&layout.to_json()).unwrap();
                assert_eq!(back, layout);
            }
        }
    }

    #[test]
    fn sites_are_deterministic() {
        assert_eq!(
            site(Context::Urban, ArchitectureStyle::Palermitan, 2.0),
            site(Context::Urban, ArchitectureStyle::Palermitan, 2.0)
        );
    }

    #[test]
    fn single_on_flat_ground_matches_the_plain_layout() {
        let layout = site(Context::Single, ArchitectureStyle::Florentine, 0.0);
        assert!(layout.terrain.is_none());
        assert!(layout.parts.iter().all(|p| p.ground == 0.0));
    }
}
