//! Whole sites: several buildings in a setting.
//!
//! - **Urban**: a cobbled street lined on both sides by attached palazzi on narrow
//!   plots, as in the centres of Florence and Palermo, opening onto a piazza with a
//!   fountain. The street climbs gently; each palazzo stands on a stone plinth.
//! - **Suburban**: villas on walled plots, each entered through a gate, along a lane.
//! - **Rural**: a villa or farmhouse on a hill, reached by a white road lined with
//!   cypresses, with an olive grove, vineyard rows and dry-stone field walls.
//! - **Single**: one building, optionally on uneven ground.
//!
//! Every building is generated by [`crate::generate`], converted to parts and placed
//! as its own group, so it stays editable and keeps its own colours.

use clap::ValueEnum;
use serde::{Deserialize, Serialize};

use crate::generate::generate;
